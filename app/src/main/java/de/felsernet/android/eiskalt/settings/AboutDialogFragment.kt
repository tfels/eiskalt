package de.felsernet.android.eiskalt.settings

import android.app.Dialog
import android.content.Intent
import android.content.pm.PackageManager
import android.os.Build
import android.os.Bundle
import android.text.TextUtils
import android.text.method.LinkMovementMethod
import android.widget.TextView
import androidx.appcompat.app.AlertDialog
import androidx.fragment.app.DialogFragment
import com.google.android.gms.oss.licenses.v2.OssLicensesMenuActivity
import de.felsernet.android.eiskalt.R

/**
 * Simple "About" dialog: app name, version, short description, beta warning, author and license.
 * Also opens the list of open-source licenses (generated by the oss-licenses-plugin).
 */
class AboutDialogFragment : DialogFragment() {

    override fun onCreateDialog(savedInstanceState: Bundle?): Dialog {
        // getText() keeps the link of the license string, so concat the parts as CharSequence
        val message = TextUtils.concat(
            getString(R.string.about_version, getVersionName()),
            "\n", getString(R.string.about_author),
            "\n\n", getString(R.string.about_description),
            "\n\n", getString(R.string.about_beta_warning),
            "\n\n", getText(R.string.about_license)
        )

        val dialog = AlertDialog.Builder(requireContext())
            .setTitle(R.string.app_name)
            .setMessage(message)
            .setPositiveButton(R.string.about_close, null)
            .setNeutralButton(R.string.about_licenses) { _, _ -> showLicenses() }
            .create()

        // make the license link clickable (the message view only exists after show())
        dialog.setOnShowListener {
            dialog.findViewById<TextView>(android.R.id.message)?.movementMethod = LinkMovementMethod.getInstance()
        }
        return dialog
    }

    private fun showLicenses() {
        OssLicensesMenuActivity.setActivityTitle(getString(R.string.about_licenses))
        startActivity(Intent(requireContext(), OssLicensesMenuActivity::class.java))
    }

    private fun getVersionName(): String {
        val context = requireContext()
        val packageInfo = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            context.packageManager.getPackageInfo(context.packageName, PackageManager.PackageInfoFlags.of(0))
        } else {
            @Suppress("DEPRECATION")
            context.packageManager.getPackageInfo(context.packageName, 0)
        }
        return packageInfo.versionName ?: "?"
    }

    companion object {
        const val TAG = "AboutDialog"
    }
}
